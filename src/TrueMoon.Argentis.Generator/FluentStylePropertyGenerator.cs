using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace TrueMoon.Argentis.Generator;

/// <summary>Generates typed style methods for opted-in UI properties.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class FluentStylePropertyGenerator : IIncrementalGenerator
{
    private const string AttributeName = "TrueMoon.Argentis.FluentStylePropertyAttribute";
    private static readonly DiagnosticDescriptor UnsupportedProperty = new(
        "ARG004", "Unsupported Fluent style property",
        "'{0}' must be a public static readonly non-null UiProperty<T> field named XProperty on a public, top-level, non-generic Element type",
        "Argentis.Generation", DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName, static (_, _) => true, static (input, _) => ReadProperty(input));
        context.RegisterSourceOutput(properties, static (output, entry) =>
        {
            if (entry.StyleProperty is { } property)
                output.AddSource($"{property.Receiver.OwnerName}.{property.FieldName}.FluentStyleProperty.g.cs", Render(property));
            else
                output.ReportDiagnostic(Diagnostic.Create(UnsupportedProperty, entry.Location, entry.Name));
        });
    }

    private static Property ReadProperty(GeneratorAttributeSyntaxContext input)
    {
        if (FluentUiProperty.TryRead(input) is { } property)
            return new(property, null, property.FieldName);

        return new(null, input.TargetNode.GetLocation(), input.TargetSymbol.ToDisplayString());
    }

    private static string Render(FluentUiProperty property)
    {
        var name = SyntaxFacts.GetKeywordKind(property.Name) == SyntaxKind.None ? property.Name : "@" + property.Name;
        var owner = property.Receiver;
        var rule = owner.IsSealed ? $"ViewStyleRule<{owner.OwnerType}>" : "ViewStyleRule<TElement>";
        var receiver = owner.IsSealed ? $"extension({rule} rule)" : $"extension<TElement>({rule} rule) where TElement : {owner.OwnerType}";
        var field = $"{owner.OwnerType}.@{property.FieldName}";
        return $$"""
            // <auto-generated/>
            #nullable enable

            namespace TrueMoon.Argentis;

            public static partial class ViewStyleExtensions
            {
                {{receiver}}
                {
                    /// <summary>Declares a fixed value for <see cref="{{field}}"/>.</summary>
                    public {{rule}} {{name}}({{property.ValueType}} value) => rule.Set({{field}}, value);

                    /// <summary>Declares a theme-dependent value for <see cref="{{field}}"/>.</summary>
                    public {{rule}} {{name}}(global::System.Func<Theme, {{property.ValueType}}> value) => rule.Set({{field}}, value);
                }
            }
            """;
    }

    private sealed record Property(FluentUiProperty? StyleProperty, Location? Location, string Name);
}
