using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace TrueMoon.Argentis.Generator;

/// <summary>Generates Fluent extensions for opted-in Argentis properties.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class FluentSetterGenerator : IIncrementalGenerator
{
    private const string AttributeName = "TrueMoon.Argentis.FluentSetterAttribute";
    private static readonly DiagnosticDescriptor UnsupportedProperty = new(
        "ARG001", "Unsupported Fluent setter property",
        "'{0}' must be a public instance property with a public non-init setter on a public, top-level, non-generic Element type and a property type usable in safe code",
        "Argentis.Generation", DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Include indexers here so an unsupported opt-in reports a build error.
        var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName, static (_, _) => true, static (input, _) => ReadProperty(input));
        context.RegisterSourceOutput(properties, static (output, property) =>
        {
            if (property.Setter is { } setter)
                output.AddSource($"{setter.Receiver.OwnerName}.{setter.Name}.FluentSetter.g.cs", Render(setter));
            else
                output.ReportDiagnostic(Diagnostic.Create(UnsupportedProperty, property.Location, property.Name));
        });
    }

    private static Property ReadProperty(GeneratorAttributeSyntaxContext input)
    {
        if (input.TargetSymbol is IPropertySymbol
            {
                DeclaredAccessibility: Accessibility.Public, IsIndexer: false, IsStatic: false,
                SetMethod: { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false }
            } property &&
            property.Type.TypeKind is not (TypeKind.Error or TypeKind.Pointer or TypeKind.FunctionPointer) &&
            FluentExtensionReceiver.TryCreate(property.ContainingType, input.SemanticModel.Compilation) is { } receiver)
        {
            return new(new(receiver, property.Name, property.Type.ToDisplayString(FluentExtensionReceiver.TypeFormat)),
                null, property.Name);
        }

        return new(null, input.TargetNode.GetLocation(), input.TargetSymbol.ToDisplayString());
    }

    private static string Render(Setter setter)
    {
        var name = SyntaxFacts.GetKeywordKind(setter.Name) == SyntaxKind.None ? setter.Name : "@" + setter.Name;
        return $$"""
            // <auto-generated/>
            #nullable enable

            namespace TrueMoon.Argentis;

            public static partial class ElementExtensions
            {
                {{setter.Receiver.Declare("element")}}
                {
                    /// <summary>Sets <see cref="{{setter.Receiver.OwnerType}}.{{name}}"/> and returns the same element.</summary>
                    public {{setter.Receiver.ReturnType}} {{name}}({{setter.ValueType}} value)
                    {
                        element.{{name}} = value;
                        return element;
                    }
                }
            }
            """;
    }

    private sealed record Property(Setter? Setter, Location? Location, string Name);
    private sealed record Setter(FluentExtensionReceiver Receiver, string Name, string ValueType);
}
