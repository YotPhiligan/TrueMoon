using Microsoft.CodeAnalysis;

namespace TrueMoon.Argentis.Generator;

/// <summary>Generates typed Fluent adapters for opted-in two-way UI bindings.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class FluentTwoWayBindingGenerator : IIncrementalGenerator
{
    private const string AttributeName = "TrueMoon.Argentis.FluentTwoWayBindingAttribute";
    private static readonly DiagnosticDescriptor UnsupportedProperty = new(
        "ARG003", "Unsupported Fluent two-way binding",
        "'{0}' must be a public static readonly non-null UiProperty<T> field named XProperty on a public, top-level, non-generic Element type",
        "Argentis.Generation", DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName, static (_, _) => true, static (input, _) => ReadProperty(input));
        context.RegisterSourceOutput(properties, static (output, entry) =>
        {
            if (entry.Binding is { } binding)
                output.AddSource($"{binding.Receiver.OwnerName}.{binding.FieldName}.FluentTwoWayBinding.g.cs", Render(binding));
            else
                output.ReportDiagnostic(Diagnostic.Create(UnsupportedProperty, entry.Location, entry.Name));
        });
    }

    private static Property ReadProperty(GeneratorAttributeSyntaxContext input)
    {
        if (FluentUiProperty.TryRead(input) is { } binding)
            return new(binding, null, binding.FieldName);

        return new(null, input.TargetNode.GetLocation(), input.TargetSymbol.ToDisplayString());
    }

    private static string Render(FluentUiProperty binding) => $$"""
        // <auto-generated/>
        #nullable enable

        using TrueMoon.Argentis.Views;

        namespace TrueMoon.Argentis;

        public static partial class ElementExtensions
        {
            {{binding.Receiver.Declare("element")}}
            {
                /// <summary>Binds <see cref="{{binding.Receiver.OwnerType}}.@{{binding.FieldName}}"/> to a notifying source property in both directions.</summary>
                /// <param name="source">The source whose property is bound.</param>
                /// <param name="selector">A direct public readable and writable property of the matching value type.</param>
                /// <returns>The same concrete element.</returns>
                public {{binding.Receiver.ReturnType}} Bind{{binding.Name}}TwoWay<TSource>(
                    TSource source,
                    global::System.Linq.Expressions.Expression<global::System.Func<TSource, {{binding.ValueType}}>> selector)
                    where TSource : class, global::System.ComponentModel.INotifyPropertyChanged =>
                    BindTwoWay(element, {{binding.Receiver.OwnerType}}.@{{binding.FieldName}}, source, selector);

                /// <summary>Binds <see cref="{{binding.Receiver.OwnerType}}.@{{binding.FieldName}}"/> in both directions to the current data context.</summary>
                /// <param name="context">The owner of the replaceable notifying source.</param>
                /// <param name="selector">A direct public readable and writable property of the matching value type.</param>
                /// <returns>The same concrete element.</returns>
                public {{binding.Receiver.ReturnType}} Bind{{binding.Name}}TwoWay<TData>(
                    global::TrueMoon.Argentis.Bindings.IDataContext<TData> context,
                    global::System.Linq.Expressions.Expression<global::System.Func<TData, {{binding.ValueType}}>> selector)
                    where TData : class, global::System.ComponentModel.INotifyPropertyChanged =>
                    BindTwoWay(element, {{binding.Receiver.OwnerType}}.@{{binding.FieldName}}, context, selector);
            }

            {{binding.Receiver.DeclareControl("control")}}
                where TData : class, global::System.ComponentModel.INotifyPropertyChanged
            {
                /// <summary>Binds the control to the current data context in both directions.</summary>
                public {{binding.Receiver.ControlType}} Bind{{binding.Name}}TwoWay(
                    global::System.Linq.Expressions.Expression<global::System.Func<TData, {{binding.ValueType}}>> selector) =>
                    control.BindTwoWay({{binding.Receiver.OwnerType}}.@{{binding.FieldName}}, selector);
            }

            {{binding.Receiver.DeclareControl("control")}}
            {
                /// <summary>Binds the control to an explicit stable source in both directions.</summary>
                public {{binding.Receiver.ControlType}} Bind{{binding.Name}}TwoWay<TSource>(TSource source,
                    global::System.Linq.Expressions.Expression<global::System.Func<TSource, {{binding.ValueType}}>> selector)
                    where TSource : class, global::System.ComponentModel.INotifyPropertyChanged =>
                    control.BindTwoWay({{binding.Receiver.OwnerType}}.@{{binding.FieldName}}, source, selector);

                /// <summary>Binds the control to an explicit replaceable context in both directions.</summary>
                public {{binding.Receiver.ControlType}} Bind{{binding.Name}}TwoWay<TSource>(
                    global::TrueMoon.Argentis.Bindings.IDataContext<TSource> context,
                    global::System.Linq.Expressions.Expression<global::System.Func<TSource, {{binding.ValueType}}>> selector)
                    where TSource : class, global::System.ComponentModel.INotifyPropertyChanged =>
                    control.BindTwoWay({{binding.Receiver.OwnerType}}.@{{binding.FieldName}}, context, selector);
            }
        }
        """;

    private sealed record Property(FluentUiProperty? Binding, Location? Location, string Name);
}
