using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace TrueMoon.Argentis.Generator;

/// <summary>Generates subscriptions to opted-in events owned by the receiver.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class FluentEventGenerator : IIncrementalGenerator
{
    private const string AttributeName = "TrueMoon.Argentis.FluentEventAttribute";
    private static readonly DiagnosticDescriptor UnsupportedEvent = new(
        "ARG002", "Unsupported Fluent event",
        "'{0}' must be a public instance event on a public, top-level, non-generic Element type with a valid receiver name other than 'handler' or 'T'",
        "Argentis.Generation", DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var events = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName, static (_, _) => true, static (input, _) => ReadEvent(input));
        context.RegisterSourceOutput(events, static (output, entry) =>
        {
            if (entry.Subscription is { } subscription)
                output.AddSource($"{subscription.Receiver.OwnerName}.{subscription.Name}.FluentEvent.g.cs", Render(subscription));
            else
                output.ReportDiagnostic(Diagnostic.Create(UnsupportedEvent, entry.Location, entry.Name));
        });
    }

    private static Event ReadEvent(GeneratorAttributeSyntaxContext input)
    {
        if (input.TargetSymbol is IEventSymbol { DeclaredAccessibility: Accessibility.Public, IsStatic: false } @event &&
            @event.Type.TypeKind == TypeKind.Delegate &&
            FluentExtensionReceiver.TryCreate(@event.ContainingType, input.SemanticModel.Compilation) is { } receiver &&
            input.Attributes[0].ConstructorArguments is [{ Value: string receiverName }] &&
            receiverName is not ("handler" or "T") && SyntaxFacts.IsValidIdentifier(receiverName) &&
            SyntaxFacts.GetKeywordKind(receiverName) == SyntaxKind.None)
        {
            var handlerType = @event.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated)
                .ToDisplayString(FluentExtensionReceiver.TypeFormat);
            return new(new(receiver, receiverName, @event.Name, handlerType), null, @event.Name);
        }

        return new(null, input.TargetNode.GetLocation(), input.TargetSymbol.ToDisplayString());
    }

    private static string Render(Subscription subscription)
    {
        var receiver = subscription.ReceiverName;
        return $$"""
            // <auto-generated/>
            #nullable enable

            namespace TrueMoon.Argentis;

            public static partial class ElementExtensions
            {
                {{subscription.Receiver.Declare(receiver)}}
                {
                    /// <summary>Handles <see cref="{{subscription.Receiver.OwnerType}}.@{{subscription.Name}}"/> for the element's lifetime, including after reattachment.</summary>
                    public {{subscription.Receiver.ReturnType}} On{{subscription.Name}}({{subscription.HandlerType}} handler)
                    {
                        global::System.ArgumentNullException.ThrowIfNull({{receiver}});
                        global::System.ArgumentNullException.ThrowIfNull(handler);
                        {{receiver}}.VerifyAccess();
                        {{receiver}}.@{{subscription.Name}} += handler;
                        return {{receiver}};
                    }
                }
            }
            """;
    }

    private sealed record Event(Subscription? Subscription, Location? Location, string Name);
    private sealed record Subscription(FluentExtensionReceiver Receiver, string ReceiverName, string Name, string HandlerType);
}
